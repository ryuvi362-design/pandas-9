import pandas as pd

dates = pd.Series([
    '12-01-2026',
    '25-03-2025',
    '08-07-2024',
    '19-11-2023',
    '30-09-2022'
])

dates = pd.to_datetime(dates, format='%d-%m-%Y')

print(dates)

movies = pd.DataFrame({
    'movie': ['Pathaan', 'Jawan', 'Dangal', 'Animal'],
    'release_date': ['25-01-2023', '07-09-2023', '23-12-2016', '01-12-2023']
})

movies['release_date'] = pd.to_datetime(
    movies['release_date'], format='%d-%m-%Y'
)

movies['year'] = movies['release_date'].dt.year
movies['month'] = movies['release_date'].dt.month
movies['day'] = movies['release_date'].dt.day

print(movies)

dates = pd.date_range(start=pd.Timestamp.today().normalize(), periods=7)

print(dates.tolist())

subscriptions = pd.DataFrame({
    'user_id': [101, 102, 103, 104],
    'start_date': ['01-01-2026', '15-05-2026', '01-08-2026', '20-09-2026']
})

subscriptions['start_date'] = pd.to_datetime(
    subscriptions['start_date'], format='%d-%m-%Y'
)

today = pd.Timestamp.today().normalize()

subscriptions['tenure_days'] = (today - subscriptions['start_date']).dt.days

print(subscriptions)

